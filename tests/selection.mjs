import assert from 'node:assert/strict';
import { RowSelection, moveRows } from '../src/selection.js';
const rows = 'abcdef'.split('').map(id=>({id}));
const p = {id:'p', samples:rows, selected:'b'};
const selection = new RowSelection();
selection.reconcile(p);
selection.click('d',{metaKey:true},rows.map(s=>s.id));
assert.deepEqual([...selection.ids],['b','d']);
selection.click('f',{shiftKey:true},rows.map(s=>s.id));
assert.deepEqual([...selection.ids],['d','e','f']);
selection.click('b',{ctrlKey:true},rows.map(s=>s.id));
assert.deepEqual([...selection.ids],['d','e','f','b']);
assert.deepEqual(moveRows(rows,['b','d'],'f',true).map(s=>s.id),['a','c','e','f','b','d']);
assert.deepEqual(moveRows(rows,['b','d'],'a').map(s=>s.id),['b','d','a','c','e','f']);
assert.deepEqual(moveRows(rows,['b','d'],'d').map(s=>s.id),rows.map(s=>s.id));
selection.reconcile({...p,id:'next',selected:'c'});
assert.deepEqual([...selection.ids],['c']);
selection.reconcile({...p,id:'next',selected:'f'});
assert.deepEqual([...selection.ids],['f']);
console.log('Selection: modifier ranges, stable group moves, and program reset passed.');
